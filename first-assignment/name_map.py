def canon(src, name):
    """Map a raw exercise name to its canonical name.

    Args:
        src: source number, 1 to 3.
        name: raw exercise name.

    Returns:
        tuple of str, canonical name, confidence and note; unknown names map to themselves with confidence 'identity'.
    """
    M={1:M1,2:M2,3:M3}[src]
    if name in M: return M[name][0], M[name][1], M[name][2]
    return name, 'identity', ''
